/**
 * 快速根据 ID 获取成就对象
 */
export const ACHIEVEMENTS_MAP = new Map<string, SteamAchievement>(
  STEAM_ACHIEVEMENTS.map(ach => [ach.id, ach])
);

/**
 * 获取与某个地图节点直接相关联的所有成就
 */
export function getAchievementsForMap(mapId: string): SteamAchievement[] {
  return STEAM_ACHIEVEMENTS.filter(ach => ach.relatedMapIds.includes(mapId));
}

/**
 * 获取所有被标记为「本周目防错过」的高危成就（做错特定操作即本周目永久无法完成，必须NG+重来）
 */
export const MISSABLE_ACHIEVEMENTS = STEAM_ACHIEVEMENTS.filter(ach => ach.isMissable);
